// Project lat/lng to percentage coordinates on an equirectangular world map
function project(lat: number, lng: number): { x: number; y: number } {
  // x: -180 to 180 -> 0 to 100
  const x = ((lng + 180) / 360) * 100;
  // y: 90 to -90 -> 0 to 100 (clamp between 80 and -60 for natural map fit)
  const clampedLat = Math.max(-60, Math.min(80, lat));
  const y = ((90 - clampedLat) / 150) * 100;
  return { 
    x: Number(x.toFixed(1)), 
    y: Number(y.toFixed(1)) 
  };
}

